package schemata

import (
	"fmt"
	"go/ast"
)

// The injected identifiers. They are deliberately long and prefixed: a
// schematized package gains these names in its package block, and a
// collision would break the user's build rather than one mutant. Any
// package that already uses one of them is declined wholesale by
// CheckCollisions.
const (
	guardFunc   = "gomutantsSchemaOn"
	activeVar   = "gomutantsSchemaActive"
	parseFunc   = "gomutantsSchemaParse"
	importAlias = "gomutantsSchemaOS"

	// HelperFile is the base name the helper is injected under. It does not
	// exist on disk; the -overlay entry conjures it into the package
	// directory, which cmd/go supports for files that are not there.
	HelperFile = "gomutants_schema.go"

	// ActiveEnv names the mutant to activate. Read once, at init.
	ActiveEnv = "GOMUTANTS_ACTIVE"
)

// helperSource renders the guard file for one package.
//
// The "os" import is aliased because a package may declare a package-level
// identifier named os, and Go forbids the same name in a file block and its
// package block. The integer parse is hand-rolled for the same reason
// applied to a second import: fewer injected names, fewer ways to collide.
//
// Reading the environment in a package-level variable is what makes
// package-level mutants work. Go initializes package-level variables in
// dependency order, so an initializer that calls the guard is ordered after
// the variable the guard reads — which is why Go does not have the "static
// mutant" limitation Stryker documents for C# and JavaScript.
func helperSource(pkgName string) []byte {
	return []byte(fmt.Sprintf(`// Code generated by gomutants (mutant schemata). DO NOT EDIT.

package %s

import %s "os"

var %s = %s(%s.Getenv(%q))

func %s(s string) int {
	n := 0
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c < '0' || c > '9' {
			return 0
		}
		n = n*10 + int(c-'0')
	}
	return n
}

func %s(id int) bool { return id != 0 && id == %s }
`, pkgName, importAlias, activeVar, parseFunc, importAlias, ActiveEnv, parseFunc, guardFunc, activeVar))
}

// CheckCollisions reports why a package cannot be schematized because it
// already uses one of the injected names, or "" when it is clear.
func CheckCollisions(files []*ast.File) string {
	reserved := map[string]bool{
		guardFunc: true, activeVar: true, parseFunc: true, importAlias: true,
	}
	for _, f := range files {
		for _, d := range f.Decls {
			for _, name := range declaredNames(d) {
				if reserved[name] {
					return fmt.Sprintf("package already declares %q", name)
				}
			}
		}
	}
	return ""
}

func declaredNames(d ast.Decl) []string {
	var out []string
	switch decl := d.(type) {
	case *ast.FuncDecl:
		if decl.Name != nil {
			out = append(out, decl.Name.Name)
		}
	case *ast.GenDecl:
		for _, spec := range decl.Specs {
			switch sp := spec.(type) {
			case *ast.ValueSpec:
				for _, id := range sp.Names {
					out = append(out, id.Name)
				}
			case *ast.TypeSpec:
				out = append(out, sp.Name.Name)
			case *ast.ImportSpec:
				if sp.Name != nil {
					out = append(out, sp.Name.Name)
				}
			}
		}
	}
	return out
}
